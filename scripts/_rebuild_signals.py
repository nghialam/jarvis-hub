d("def api_get_signals():")
d('    """Get unified signal feed from both tables, merged and deduplicated."""')
d("    if not db:")
d('        return jsonify({"signals": [], "error": "DB not initialized"})')
d("")
d("    try:")
d("         # Optional filters")
d('        signal_filter = request.args.get("signal", "").upper()')
d('        severity_filter = request.args.get("severity", "").upper()')
d('        symbol_filter = request.args.get("symbol", "").upper()')
d('        only_unread = request.args.get("unread", "false").lower() == "true"')
d("")
d("         # Fetch signals from BOTH tables")
d("        all_signals = []")
d('        source_counts = {"signals_log": 0, "trading_alerts": 0}')
d("")
d("        try:")
d("             # Table 1: signals_log (from trading bot)")
d('            rows = db._c().execute("""')
d("                SELECT id, symbol, 'TRADING_BOT' as source, signal_type,")
d("                       CAST(strength AS TEXT) as severity, price, details,")
d("                       detected_at as timestamp, delivered as is_delivered, delivery_channel")
d('                FROM signals_log WHERE 1=1')
d('             """).fetchall()')
d("            for row in rows:")
d("                r = dict(row)")
d("                 # Apply filters")
d('                if signal_filter and r["signal_type"] != signal_filter:')
d("                    continue")
d('                if symbol_filter and r["symbol"] != symbol_filter:')
d("                    continue")
d("                all_signals.append(r)")
d('                source_counts["signals_log"] += 1')
d("        except Exception as e:")
d('            print(f"[SIGNALS] signals_log error: {{e}}")')
d("")
d("        try:")
d("             # Table 2: trading_alerts (from auto-scan engine)")
d('            rows = db._c().execute("""')
d("                SELECT id, symbol, 'AUTO_SCAN' as source, signal_type,")
d('                       severity AS severity,')
d("                       CAST(alert_data->>'price' AS REAL) as price,")
d("                       alert_data,")
d("                       timestamp as detected_at,")
d("                       CASE WHEN status='read' THEN 1 ELSE 0 END as is_delivered,")
d("                       delivery_channel")
d('                FROM trading_alerts')
d('             """).fetchall()')
d("            for row in rows:")
d("                r = dict(row)")
d("                 # Parse JSON alert_data if string")
d('                raw = r.get("alert_data")')
d("                if isinstance(raw, str):")
d("                    try:")
d("                        import json as _json")
d('                        r["alert_parsed"] = _json.loads(raw)')
d("                    except Exception:")
d('                        r["alert_parsed"] = None')
d("                else:")
d('                    r["alert_parsed"] = raw')
d("")
d('                del r["alert_data"]')
d("")
d("                 # Apply filters")
d('                if signal_filter and r["signal_type"] != signal_filter:')
d("                    continue")
d('                if symbol_filter and r["symbol"] != symbol_filter:')
d("                    continue")
d('                if only_unread and r.get("is_delivered"):')
d("                    continue")
d("")
d("                all_signals.append(r)")
d('                source_counts["trading_alerts"] += 1')
d("        except Exception as e:")
d('            print(f"[SIGNALS] trading_alerts error: {{e}}")')
d("")
d("         # Sort by timestamp descending (newest first)")
d('        all_signals.sort(key=lambda x: x.get("timestamp", ""), reverse=True)')
d("")
d("         # Deduplication: keep latest signal per symbol")
d("        best_by_symbol = {}")
d("        neutral_kept = []")
d("        for sig in all_signals:")
d('            sym = sig["symbol"]')
d('            stype = sig.get("signal_type", "NEUTRAL")')
d("")
d('            if stype in ("NEUTRAL", "HOLD"):')
d('                if sym not in [s["symbol"] for s in neutral_kept]:')
d("                    neutral_kept.append(sig)")
d("                continue")
d("")
d("            key = (sym, stype)")
d('            if key not in best_by_symbol or sig.get("timestamp", "") > best_by_symbol[key].get("timestamp", ""):')
d("                if key in best_by_symbol:")
d("                    old = best_by_symbol[sym]")
d('                    if old not in neutral_kept and old["symbol"] not in [s["symbol"] for s in neutral_kept]:')
d("                        neutral_kept.append(old)")
d("                best_by_symbol[key] = sig")
d("")
d("        seen_symbols_neutral = set()")
d("        deduped_neutral = []")
d("        for s in neutral_kept:")
d('            if s["symbol"] not in seen_symbols_neutral:')
d('                seen_symbols_neutral.add(s["symbol"])')
d("                deduped_neutral.append(s)")
d("")
d("        final_signals = list(best_by_symbol.values()) + deduped_neutral")
d("")
d("         return jsonify({")
d('             "signals": final_signals,')
d('             "counts": {"total": len(final_signals), "by_source": source_counts}')
d("         })")
d("    except Exception as e:")
d('        print(f"[SIGNALS] Error: {{e}}")')
d('        return jsonify({"signals": [], "error": str(e)}, 500)')
d("")
d("")

