# api_signal_append function
d('@app.route("/api/signals/add", methods=["POST"])')
d("def api_signal_append():")
d('     """Manual signal entry via dashboard or API."""')
d("    if not db:")
d('        return jsonify({"success": False, "error": "DB not initialized"}), 500')
d("")
d('    data = request.get_json() or {}')
d('    symbol = str(data.get("symbol", "")).strip().upper()')
d('    signal_type = str(data.get("signal", "")).upper()')
d('    strength = float(data.get("strength", 0))')
d("")
d("    if not symbol or len(symbol) < 2:")
d('        return jsonify({"success": False, "error": "Invalid symbol"}), 400')
d('    valid_types = ("BUY", "SELL", "HOLD", "STOP_LOSS", "TAKE_PROFIT", "WATCH", "NEUTRAL")')
d("    if signal_type and signal_type not in valid_types:")
d('        return jsonify({"success": False, "error": "Invalid signal type"}), 400')
d("")
d('    details = {k: v for k, v in data.items() if k not in ("symbol", "signal", "strength")}')
d("")
d("     # Persist to signals_log")
d("    try:")
d("        import json as _json")
d('        db._c().execute("""')
d('            INSERT INTO signals_log (symbol, signal_type, strength, price, details, detected_at)')
d('            VALUES (?, ?, ?, ?, ?, ?)')
d('         """, (symbol, signal_type if signal_type else "NEUTRAL", strength,')
d('             data.get("price"), _json.dumps(details), _utc_now_iso()))')
d("        db._conn.commit()")
d('        print(f"[SIGNALS] Added {{symbol}}: {{signal_type}} ({{strength}})")') 
d('        return jsonify({"success": True})')
d("    except sqlite3.Error as e:")
d('        if "no such table" in str(e):')
d('            return jsonify({"success": False, "error": "signals_log not found"}), 500')
d('        print(f"[SIGNALS] Insert error: {{e}}")')
d('        return jsonify({"success": False, "error": str(e)}), 500')
d("")
d("")

