# api_signal_for_symbol function  
d('@app.route("/api/signals/symbol/<symbol>", methods=["GET"])')
d("def api_signal_for_symbol(symbol):")
d('     """Get all signals for a specific symbol full history."""')
d("    if not db:")
d('        return jsonify({"symbol": symbol, "signals": []})')
d("")
d("    symbol = str(symbol).upper().strip()")
